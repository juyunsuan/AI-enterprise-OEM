CREATE TABLE `workbuddy_cloud_commands` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `user_id` VARCHAR(64) NOT NULL,
    `account_id` INTEGER NOT NULL,
    `agent_id` VARCHAR(64) NOT NULL DEFAULT '',
    `version_id` VARCHAR(64) NOT NULL DEFAULT '',
    `conversation_id` INTEGER NOT NULL DEFAULT 0,
    `session_id` VARCHAR(128) NOT NULL DEFAULT '',
    `endpoint` VARCHAR(500) NOT NULL DEFAULT '',
    `command_code` VARCHAR(40) NOT NULL,
    `kind` VARCHAR(16) NOT NULL DEFAULT 'prompt',
    `title` VARCHAR(200) NOT NULL DEFAULT '',
    `payload` JSON NOT NULL DEFAULT (JSON_OBJECT()),
    `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    `progress_text` TEXT NOT NULL DEFAULT (''),
    `result` JSON NOT NULL DEFAULT (JSON_OBJECT()),
    `error` VARCHAR(500) NOT NULL DEFAULT '',
    `cancel_requested` BOOLEAN NOT NULL DEFAULT false,
    `source_task_id` INTEGER NOT NULL DEFAULT 0,
    `schedule_id` INTEGER NOT NULL DEFAULT 0,
    `retry_count` INTEGER NOT NULL DEFAULT 0,
    `dispatched_at` DATETIME(3) NULL,
    `finished_at` DATETIME(3) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` DATETIME(3) NOT NULL,
    UNIQUE INDEX `workbuddy_cloud_commands_command_code_key`(`command_code`),
    INDEX `workbuddy_cloud_commands_account_id_status_id_idx`(`account_id`, `status`, `id`),
    INDEX `workbuddy_cloud_commands_user_id_created_at_idx`(`user_id`, `created_at`),
    INDEX `workbuddy_cloud_commands_schedule_id_created_at_idx`(`schedule_id`, `created_at`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `workbuddy_cloud_schedules` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `user_id` VARCHAR(64) NOT NULL,
    `account_id` INTEGER NOT NULL,
    `title` VARCHAR(80) NOT NULL,
    `instruction` TEXT NOT NULL,
    `payload` JSON NOT NULL DEFAULT (JSON_OBJECT()),
    `schedule_type` VARCHAR(16) NOT NULL DEFAULT 'recurring',
    `schedule_config` JSON NOT NULL DEFAULT (JSON_OBJECT()),
    `scheduled_at` DATETIME(3) NULL,
    `status` VARCHAR(16) NOT NULL DEFAULT 'enabled',
    `last_run_at` DATETIME(3) NULL,
    `last_status` VARCHAR(16) NOT NULL DEFAULT '',
    `last_error` VARCHAR(500) NOT NULL DEFAULT '',
    `run_count` INTEGER NOT NULL DEFAULT 0,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `updated_at` DATETIME(3) NOT NULL,
    INDEX `workbuddy_cloud_schedules_user_id_status_idx`(`user_id`, `status`),
    INDEX `workbuddy_cloud_schedules_status_schedule_type_scheduled_at_idx`(`status`, `schedule_type`, `scheduled_at`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `workbuddy_cloud_schedule_runs` (
    `id` INTEGER NOT NULL AUTO_INCREMENT,
    `schedule_id` INTEGER NOT NULL,
    `account_id` INTEGER NOT NULL,
    `user_id` VARCHAR(64) NOT NULL,
    `status` VARCHAR(16) NOT NULL DEFAULT 'queued',
    `command_code` VARCHAR(40) NOT NULL DEFAULT '',
    `conversation_id` INTEGER NOT NULL DEFAULT 0,
    `error` VARCHAR(500) NOT NULL DEFAULT '',
    `started_at` DATETIME(3) NULL,
    `finished_at` DATETIME(3) NULL,
    `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    INDEX `workbuddy_cloud_schedule_runs_schedule_id_created_at_idx`(`schedule_id`, `created_at`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
