-- 租赁管理小程序：门店、租品、顾客、员工、租单、验车与 SCRM 外发箱
CREATE TABLE `rental_shops` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `owner_user_id` VARCHAR(64) NOT NULL,
  `name` VARCHAR(120) NOT NULL,
  `shop_code` VARCHAR(16) NOT NULL,
  `logo` VARCHAR(500) NOT NULL DEFAULT '',
  `service_phone` VARCHAR(32) NOT NULL DEFAULT '',
  `address` VARCHAR(200) NOT NULL DEFAULT '',
  `status` VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  `theme_json` JSON NOT NULL,
  `trade_json` JSON NOT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `rental_shops_shop_code_key`(`shop_code`),
  INDEX `rental_shops_owner_user_id_status_idx`(`owner_user_id`, `status`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `rental_items` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `shop_id` INTEGER NOT NULL,
  `category` VARCHAR(60) NOT NULL DEFAULT '',
  `name` VARCHAR(120) NOT NULL,
  `cover` VARCHAR(500) NOT NULL DEFAULT '',
  `images_json` JSON NOT NULL,
  `description` TEXT NOT NULL,
  `attributes_json` JSON NOT NULL,
  `daily_rate` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `deposit` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `stock` INTEGER NOT NULL DEFAULT 1,
  `status` VARCHAR(16) NOT NULL DEFAULT 'ONLINE',
  `sort_order` INTEGER NOT NULL DEFAULT 0,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  INDEX `rental_items_shop_id_status_sort_order_idx`(`shop_id`, `status`, `sort_order`),
  INDEX `rental_items_shop_id_category_idx`(`shop_id`, `category`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `rental_customers` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `shop_id` INTEGER NOT NULL,
  `openid` VARCHAR(64) NOT NULL,
  `union_id` VARCHAR(64) NOT NULL DEFAULT '',
  `nickname` VARCHAR(120) NOT NULL DEFAULT '',
  `avatar` VARCHAR(500) NOT NULL DEFAULT '',
  `phone` VARCHAR(32) NOT NULL DEFAULT '',
  `source` VARCHAR(16) NOT NULL DEFAULT 'MINIPROGRAM',
  `gender` TINYINT NOT NULL DEFAULT 0,
  `city` VARCHAR(60) NOT NULL DEFAULT '',
  `remark` VARCHAR(500) NOT NULL DEFAULT '',
  `crm_customer_id` INTEGER NOT NULL DEFAULT 0,
  `status` VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  `last_login_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `rental_customers_shop_id_openid_key`(`shop_id`, `openid`),
  INDEX `rental_customers_shop_id_phone_idx`(`shop_id`, `phone`),
  PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `rental_staffs` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `shop_id` INTEGER NOT NULL,
  `name` VARCHAR(60) NOT NULL,
  `phone` VARCHAR(32) NOT NULL,
  `staff_code` VARCHAR(32) NOT NULL,
  `role` VARCHAR(16) NOT NULL DEFAULT 'CLERK',
